static Lang g_lang = LANG_FR;

void set_lang(Lang l) { if (l < LANG_COUNT) g_lang = l; }
Lang lang()           { return g_lang; }

const char* T(StrId id)        { return (id < STR_COUNT) ? TABLE[g_lang][id] : "?"; }
const char* lang_name(Lang l)  { return (l < LANG_COUNT) ? NAMES[l] : "?"; }

const char* title_of(uint8_t f) { return (f < 6) ? TABLE[g_lang][STR_FT_KENJI + f] : ""; }

int rules_lines(GameId g) {
    switch (g) {
        case GAME_FIGHT: return RULES_FIGHT_N;
        default: return 0;
    }
}

const char* rules_line(GameId g, int i) {
    switch (g) {
        case GAME_FIGHT: return (i < RULES_FIGHT_N) ? RULES_FIGHT[g_lang][i] : "";
        default: return "";
    }
}

int         controls_lines()      { return CONTROLS_N; }
const char* controls_line(int i)  { return (i < CONTROLS_N) ? CONTROLS[g_lang][i] : ""; }
int         keys_lines()          { return KEYS_N; }
const char* keys_line(int i)      { return (i < KEYS_N) ? KEYS[g_lang][i] : ""; }

