export const FIGHTER_ORDER: FighterId[] = [
  'kenji',
  'krowen',
  'meilin',
  'titan',
  'nyxia',
  'malakor',
];

/**
 * Génère l'échelle de 5 combats du Mode Histoire :
 * 3 adversaires variés -> Le Rival juré du personnage (Match 4) -> Seigneur Malakor en Boss Final (Match 5).
 */
export function buildStoryLadder(playerId: FighterId): FighterId[] {
  const player = FIGHTERS[playerId];
  const rivalId = player.rivalId;
  const others = FIGHTER_ORDER.filter(
    (id) => id !== playerId && id !== rivalId && id !== 'malakor'
  );

  // Si le joueur incarne Malakor lui-même, il affronte les 4 héros puis son Rival Mei-Lin en Boss ultime !
  if (playerId === 'malakor') {
    return ['titan', 'nyxia', 'krowen', 'kenji', 'meilin'];
  }

  // Si le rival est déjà Malakor (cas de Mei-Lin), on prend les 4 autres combattants puis Malakor
  if (rivalId === 'malakor') {
    const fourOpponents = FIGHTER_ORDER.filter((id) => id !== playerId && id !== 'malakor');
    return [...fourOpponents, 'malakor'];
  }

  return [...others.slice(0, 3), rivalId, 'malakor'];
}
